    // Allow digits, decimal, degree symbol, letters C F K R, and backspace
    if (!Character.isDigit(c) && c != '.' && c != '°' && 
        c != 'C' && c != 'F' && c != 'K' && c != 'R' &&
        c != java.awt.event.KeyEvent.VK_BACK_SPACE) {
        evt.consume();
    }
