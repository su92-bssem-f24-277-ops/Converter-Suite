private void autoConvert() {
    try {
        if (jTextField1.getText().trim().isEmpty()) {
            jTextField2.setText("");
            return;
        }

        String from = jComboBox1.getSelectedItem().toString();
        String to = jComboBox2.getSelectedItem().toString();

        if (from.equals("Select Temperature:") || to.equals("Select Temperature:")) {
            jTextField2.setText("");
            return;
        }

        double value = Double.parseDouble(jTextField1.getText());
        double celsius;

        // Convert FROM → Celsius
        if (from.contains("Celsius")) celsius = value;
        else if (from.contains("Fahrenheit")) celsius = (value - 32) * 5 / 9;
        else if (from.contains("Kelvin")) celsius = value - 273.15;
        else celsius = (value - 491.67) * 5 / 9;

        double result;

        // Convert Celsius → TO unit
        if (to.contains("Celsius")) result = celsius;
        else if (to.contains("Fahrenheit")) result = (celsius * 9 / 5) + 32;
        else if (to.contains("Kelvin")) result = celsius + 273.15;
        else result = (celsius + 273.15) * 9 / 5;
        String toUnit;
        if (to.contains("Celsius")) toUnit = "°C";
        else if (to.contains("Fahrenheit")) toUnit = "°F";
        else if (to.contains("Kelvin")) toUnit = "K";
        else toUnit = "°R";

        // Input unit suffix
        String fromUnit;
        if (from.contains("Celsius")) fromUnit = "°C";
        else if (from.contains("Fahrenheit")) fromUnit = "°F";
        else if (from.contains("Kelvin")) fromUnit = "K";
        else fromUnit = "°R";

        jTextField1.setText(value + fromUnit);
        jTextField2.setText(String.format("%.2f%s", result, toUnit));

    }catch (Exception e) {
        jTextField2.setText("");
    }
}




